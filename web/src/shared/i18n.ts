const dictionaries = { ru, en }

/** Translates UI strings for the current locale preference; {name} placeholders are filled from vars. */
export function useI18n() {
    const current = usePreference(locale)
    const lang = computed(() => (current.value.value === 'en' ? 'en' : 'ru'))

    function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
        const template: string = dictionaries[lang.value][key] ?? ru[key]
        return template.replaceAll(/\{(\w+)\}/g, (_match: string, name: string) =>
            String(vars[name] ?? ''),
        )
    }

    return { t, lang }
}
